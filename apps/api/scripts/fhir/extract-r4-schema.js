#!/usr/bin/env node
/**
 * Extract the parts of the official HL7 FHIR R4 JSON schema that the
 * /fhir/r4 API returns, for use as a test fixture (#1435).
 *
 * The full schema (https://hl7.org/fhir/R4/fhir.schema.json.zip, ~3.4 MB)
 * covers all 145 resources. This keeps every definition reachable from the
 * resources we serve — copied verbatim — and narrows `ResourceList` (the
 * polymorphic `Bundle.entry.resource`) to those resources.
 *
 *   curl -sLO https://hl7.org/fhir/R4/fhir.schema.json.zip && unzip fhir.schema.json.zip
 *   node scripts/fhir/extract-r4-schema.js fhir.schema.json
 */
const fs = require('fs');
const path = require('path');

const ROOTS = [
  'Patient',
  'Encounter',
  'Observation',
  'Bundle',
  'CapabilityStatement',
  'OperationOutcome',
];
const OUT = path.resolve(
  __dirname,
  '../../src/modules/fhir/__tests__/fixtures/fhir-r4-subset.schema.json'
);

const source = process.argv[2];
if (!source) {
  console.error('usage: extract-r4-schema.js <path to fhir.schema.json>');
  process.exit(1);
}
const full = JSON.parse(fs.readFileSync(source, 'utf8'));

function* refs(node) {
  if (Array.isArray(node)) for (const n of node) yield* refs(n);
  else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) {
      if (k === '$ref' && typeof v === 'string') yield v.split('/').pop();
      else yield* refs(v);
    }
  }
}

const keep = new Set();
const stack = [...ROOTS];
while (stack.length) {
  const name = stack.pop();
  if (keep.has(name) || name === 'ResourceList') continue;
  keep.add(name);
  stack.push(...refs(full.definitions[name]));
}

const definitions = {};
for (const name of [...keep].sort()) definitions[name] = full.definitions[name];
definitions.ResourceList = { oneOf: ROOTS.map((r) => ({ $ref: `#/definitions/${r}` })) };

const subset = {
  $schema: full.$schema,
  id: full.id,
  description: `Subset of the official FHIR R4 (4.0.1) JSON schema: ${ROOTS.join(', ')}. Generated by scripts/fhir/extract-r4-schema.js — do not edit.`,
  discriminator: {
    propertyName: 'resourceType',
    mapping: Object.fromEntries(ROOTS.map((r) => [r, `#/definitions/${r}`])),
  },
  oneOf: ROOTS.map((r) => ({ $ref: `#/definitions/${r}` })),
  definitions,
};

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(subset) + '\n');
console.log(
  `wrote ${Object.keys(definitions).length} definitions to ${path.relative(process.cwd(), OUT)}`
);
